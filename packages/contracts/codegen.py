"""Regenerate typed Pydantic models from the contract specs.

Usage:
    python packages/contracts/codegen.py            # regenerate in place
    python packages/contracts/codegen.py --check    # CI drift check (no writes)

Python output lands in services/core/src/maistro/generated/ so it is
importable as `maistro.generated.*`. Generated files are never hand-edited;
the --check mode regenerates into a temp dir and fails if the committed
output differs (CONTRACTS.md §6).
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

CONTRACTS_DIR = Path(__file__).resolve().parent
REPO_ROOT = CONTRACTS_DIR.parent.parent
PY_OUT = REPO_ROOT / "services" / "core" / "src" / "maistro" / "generated"

OPENAPI_SPECS = {
    "trend-radar.yaml": "trend_radar.py",
    "f1x8.yaml": "f1x8.py",
    "sentiment.yaml": "sentiment.py",
    "lenceus.yaml": "lenceus.py",
}

HEADER = '"""Generated by packages/contracts/codegen.py — DO NOT EDIT."""\n'

COMMON_ARGS = [
    "--output-model-type", "pydantic_v2.BaseModel",
    "--target-python-version", "3.12",
    "--use-annotated",
    "--use-double-quotes",
    "--use-schema-description",
    "--disable-timestamp",
    "--use-standard-collections",
    "--use-union-operator",
]


def run_codegen(args: list[str]) -> None:
    cmd = [sys.executable, "-m", "datamodel_code_generator", *args, *COMMON_ARGS]
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode != 0:
        sys.stderr.write(result.stdout + result.stderr)
        raise SystemExit(f"codegen failed: {' '.join(args)}")


def generate(out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "__init__.py").write_text(HEADER, encoding="utf-8")

    for spec, module in OPENAPI_SPECS.items():
        run_codegen([
            "--input", str(CONTRACTS_DIR / "openapi" / spec),
            "--input-file-type", "openapi",
            "--output", str(out_dir / module),
        ])

    # Maistro-owned entities: one module per JSON Schema file.
    run_codegen([
        "--input", str(CONTRACTS_DIR / "schemas"),
        "--input-file-type", "jsonschema",
        "--output", str(out_dir / "entities"),
    ])
    init = out_dir / "entities" / "__init__.py"
    if not init.exists():
        init.write_text(HEADER, encoding="utf-8")


def tree_digest(root: Path) -> dict[str, str]:
    # Normalize line endings so the drift check is byte-stable across
    # Windows dev machines and Linux CI regardless of checkout settings.
    return {
        str(p.relative_to(root)).replace("\\", "/"): p.read_text(encoding="utf-8").replace(
            "\r\n", "\n"
        )
        for p in sorted(root.rglob("*.py"))
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if committed output is stale")
    opts = parser.parse_args()

    if not opts.check:
        if PY_OUT.exists():
            shutil.rmtree(PY_OUT)
        generate(PY_OUT)
        print(f"generated -> {PY_OUT}")
        return 0

    with tempfile.TemporaryDirectory() as tmp:
        fresh_dir = Path(tmp) / "generated"
        generate(fresh_dir)
        fresh = tree_digest(fresh_dir)
        committed = tree_digest(PY_OUT) if PY_OUT.exists() else {}
        if fresh == committed:
            print("codegen drift check: clean")
            return 0
        stale = sorted(
            set(fresh) ^ set(committed)
            | {k for k in set(fresh) & set(committed) if fresh[k] != committed[k]}
        )
        sys.stderr.write(
            "codegen drift detected — run `python packages/contracts/codegen.py`\n"
            + "".join(f"  stale: {name}\n" for name in stale)
        )
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
