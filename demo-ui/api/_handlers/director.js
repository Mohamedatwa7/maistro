// POST /api/director — the AI Creative Director behind Studio Create.
// Maistro's users are marketers, not prompt engineers: they type plain words
// ("make it feel premium", "something funny with the fridge") and this
// endpoint has Claude craft the professional Higgsfield generation prompt for
// the requested artifact. It is explicitly briefed on what each artifact IS
// (a moodboard is a board, not a photo) and receives every previously
// generated stage so the campaign stays visually coherent end to end.
//
// Request:  { stage: 'mood'|'thumb'|'board'|'final',
//             userInput: string,            // optional plain-language wishes
//             campaign: { title, product, msg, angle, markets, platforms },
//             context: { mood?: {prompt, note}, thumb?: {...}, board?: {...} } }
// Response: { stage, prompt, note }
//   prompt — ready to send to Higgsfield (Soul for images, Seedance for video)
//   note   — 1-2 plain-English sentences shown to the user (what & why)

const Anthropic = require('@anthropic-ai/sdk');
const { requireSession } = require('../_auth.js');
const { brandPrompts } = require('../_kb/index.js'); // Phase 6.1: catalog and playbook come from the knowledge base (seed = today's text)
const { registerPrompt, recordGeneration } = require('../_records.js');
const PROMPT_VERSION = 'director-v1-2026-10-21'; // bump when SYSTEM or a stage brief changes
const { validate, DIRECTOR_BODY } = require('../_schemas.js');

const MODEL = 'claude-opus-4-8';

const ARTIFACTS = {
  mood: {
    label: 'Moodboard',
    target: 'Higgsfield Soul (text-to-image)',
    brief:
      'A moodboard is NOT a normal photograph. It is ONE image laid out as a designer\'s ' +
      'art-direction board: a clean collage grid of 4-6 tiles on a single canvas — color ' +
      'palette swatches, texture close-ups, lighting references, material details, and ' +
      'product-context fragments. Flat-lay board aesthetic, cohesive grading across tiles, ' +
      'subtle gaps between tiles like a curated reference board. The prompt MUST describe ' +
      'the collage/board layout explicitly or the model will produce a single ordinary image.',
  },
  thumb: {
    label: 'Thumbnail',
    target: 'Higgsfield Soul (text-to-image)',
    brief:
      'A thumbnail is ONE scroll-stopping 16:9 key visual used as the social video cover: ' +
      'a single bold subject, high contrast, cinematic lighting, shallow depth, instantly ' +
      'readable at phone size, with clean negative space reserved on one side where a short ' +
      'title will be overlaid later. No text in the image itself.',
  },
  board: {
    label: 'Storyboard',
    target: 'Higgsfield Soul (text-to-image)',
    brief:
      'A storyboard is ONE image formatted as a production storyboard sheet: exactly 6 ' +
      'sequential panels in a 3x2 grid with thin frames/gutters, the same characters, ' +
      'product and setting continuing across panels, each panel a distinct story beat from ' +
      'opening hook to final product reveal. Cinematic concept-art rendering style. The ' +
      'prompt MUST describe the 6-panel sheet layout and list the beats panel by panel.',
  },
  final: {
    label: 'Final video',
    target: 'Higgsfield Seedance 2.5 (text-to-video)',
    brief:
      'The final piece is a short (5-10s) social video generated by a text-to-video model. ' +
      'Write ONE continuous cinematic shot description: subject and action, camera movement ' +
      '(dolly/orbit/push-in...), lens and lighting, mood and pacing, environment. Present ' +
      'tense, concrete and visual. No shot lists, no cuts, no on-screen text, no captions.',
  },
  revise: {
    label: 'Final content — QC revision',
    target: 'Higgsfield Seedance 2.5 (text-to-video)',
    brief:
      'This is the REVISION PASS: the first-draft video was analyzed by F1X8 (the ' +
      'engagement-scoring QC engine) and you receive its findings — the score, ranked ' +
      'risks with suggested fixes, and a structured revision brief. Rewrite the draft\'s ' +
      'original prompt into a new one that IMPLEMENTS EVERY FIX while preserving ' +
      'everything that scored well (keep the same subject, setting, palette and overall ' +
      'concept — this is a revision, not a new idea). Same format rules as a final video: ' +
      'ONE continuous cinematic shot, present tense, no cuts, no on-screen text. In the ' +
      'note, tell the user which fixes you implemented and how.',
  },
};

const systemPrompt = ({ PRODUCTS_PROMPT, BRAND_PROMPT }) =>
  'You are the AI Creative Director inside MAISTRO, Samsung Gulf\'s A-to-Z content ' +
  'platform. Marketing teammates — not prompt engineers — describe what they want in ' +
  'plain, often vague words. Your job: turn their intent into ONE professional ' +
  'generation prompt for the requested artifact, making every craft decision yourself ' +
  '(composition, lighting, lens, palette, materials, style). Never ask questions back.\n\n' +
  'VISUAL CONTINUITY IS MANDATORY: you receive the prompts and notes of everything ' +
  'already generated for this campaign. Carry the SAME palette, lighting language, ' +
  'materials and mood forward so all pieces look like one campaign — reference them ' +
  'concretely in the new prompt (name the colors, the light, the textures).\n\n' +
  'BRAND FRAME: premium Samsung look — refined, modern, uncluttered; the named product ' +
  'is the hero; regionally relevant to the target markets when people or places appear; ' +
  'never show competitor devices, logos, watermarks, or written text inside the image ' +
  '(except the reserved empty title space on thumbnails).\n\n' +
  PRODUCTS_PROMPT + '\n' +
  'When a product appears in a prompt, describe it using its catalog look line so the ' +
  'image model renders the CURRENT design — never an older generation\'s form factor.\n' +
  'If campaign.referenceImageAttached is true, an OFFICIAL PRODUCT PHOTO is supplied to ' +
  'the image model as its visual reference: it carries the product\'s exact real design, ' +
  'so write the prompt around scene, mood, lighting and composition — always call the ' +
  'device "the exact product from the reference image", NEVER name or describe a ' +
  'different product than the reference (the reference outranks campaign.product if they ' +
  'disagree), and do NOT re-describe the product\'s shape in ways that could conflict ' +
  'with the reference. A reference is ONLY attached for thumbnails (single hero visuals). ' +
  'Moodboards and storyboards are generated WITHOUT it — keep the moodboard a true collage ' +
  'board and the storyboard a true 6-panel sheet, describing the product in-panel via its ' +
  'catalog look line.\n\n' +
  BRAND_PROMPT + '\n\n' +
  'Apply the playbook to every prompt: pick a leading O.B.A. principle, weave in Refined ' +
  'Wit, build palettes from the brand colors (blue present and intentional in every ' +
  'composition — name the hexes), and follow the imagery rules for the leading principle.\n\n' +
  'Keep the generation prompt under 130 words, vivid and concrete. The note is for the ' +
  'non-technical user: 1-2 friendly sentences on what you went for and how it connects ' +
  'to the earlier pieces.';

module.exports = async (req, res) => {
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type');
  if (req.method === 'OPTIONS') return res.status(204).end();
  if (req.method !== 'POST') {
    res.setHeader('Allow', 'POST, OPTIONS');
    return res.status(405).json({ error: 'method not allowed' });
  }
  if (!requireSession(req, res)) return;
  if (!process.env.ANTHROPIC_API_KEY) {
    return res.status(503).json({ error: 'ANTHROPIC_API_KEY is not configured' });
  }

  const { stage, userInput, campaign, context } = req.body || {};
  const spec = ARTIFACTS[stage];
  if (!spec) return res.status(422).json({ error: `unknown stage "${stage}" — use mood|thumb|board|final|revise` });
  if (!campaign || !campaign.title) return res.status(422).json({ error: 'campaign {title, product, msg, angle, ...} is required' });
  const problems = validate(DIRECTOR_BODY, req.body || {});
  if (problems.length) return res.status(422).json({ error: `invalid request: ${problems.slice(0, 3).join('; ')}`, problems });

  const prior = [];
  ['mood', 'thumb', 'board'].forEach((s) => {
    if (context && context[s] && context[s].prompt) {
      prior.push(
        `${ARTIFACTS[s].label.toUpperCase()} (already generated):\n` +
        `  prompt used: ${context[s].prompt}\n` +
        (context[s].note ? `  director note: ${context[s].note}\n` : '')
      );
    }
  });
  if (context && context.draft && context.draft.prompt) {
    prior.push(
      'FIRST DRAFT VIDEO (the cut being revised):\n' +
      `  original prompt: ${context.draft.prompt}\n` +
      (context.draft.note ? `  director note: ${context.draft.note}\n` : '')
    );
  }
  if (context && context.qc) {
    const q = context.qc;
    prior.push(
      'F1X8 QC FINDINGS ON THE FIRST DRAFT (implement every fix):\n' +
      (q.score != null ? `  draft score: ${q.score}/10\n` : '') +
      (q.summary ? `  summary: ${q.summary}\n` : '') +
      ((q.fixes && q.fixes.length) ? `  ranked fixes:\n${q.fixes.map((f) => '    - ' + f).join('\n')}\n` : '') +
      (q.revisionBrief && Object.keys(q.revisionBrief).length
        ? `  revision brief: ${JSON.stringify(q.revisionBrief)}\n` : '')
    );
  }

  try {
    const client = new Anthropic({ timeout: 55000, maxRetries: 1 }); // under the 60 s function limit
    const kb = await brandPrompts();
    const system = systemPrompt(kb);
    registerPrompt(`director.${stage}`, PROMPT_VERSION, `SYSTEM:\n${systemPrompt({ PRODUCTS_PROMPT: '{{PRODUCTS_PROMPT}}', BRAND_PROMPT: '{{BRAND_PROMPT}}' })}\n\nUSER: ARTIFACT TO CREATE: ${spec.label} — for ${spec.target}; WHAT THIS ARTIFACT IS: ${spec.brief}; CAMPAIGN {{campaign}}; PRIOR {{prior}}; USER INPUT {{userInput}}`, ['PRODUCTS_PROMPT', 'BRAND_PROMPT', 'campaign', 'prior', 'userInput']);
    const t0 = Date.now();
    const rec = { kind: 'claude', legacyPieceId: (campaign && campaign.id) || null, stage, model: MODEL, promptName: `director.${stage}`, promptVersion: PROMPT_VERSION, params: { max_tokens: 2000, thinking: 'adaptive', referenceImageAttached: Boolean(campaign && campaign.referenceImageAttached) }, memberId: req.member ? req.member.id : null };
    const userContent =
            `ARTIFACT TO CREATE: ${spec.label} — for ${spec.target}\n` +
            `WHAT THIS ARTIFACT IS (follow exactly): ${spec.brief}\n\n` +
            `CAMPAIGN:\n${JSON.stringify(campaign, null, 2)}\n\n` +
            (prior.length
              ? `ALREADY GENERATED — KEEP VISUAL CONTINUITY WITH ALL OF THIS:\n${prior.join('\n')}\n`
              : 'Nothing generated yet — this piece sets the campaign\'s visual language.\n') +
            `\nWHAT THE USER ASKED FOR (plain words, may be vague or empty — fill the gaps yourself):\n` +
            `"${String(userInput || '').trim() || '(they left it to you)'}"\n\n` +
            `Write the generation prompt and the user-facing note.`;
    rec.resolvedPrompt = `${system}\n\n${userContent}`; rec.userPrompt = userContent; rec.kbFingerprint = kb.kbFingerprint;
    let response;
    try {
    response = await client.messages.create({
      model: MODEL,
      max_tokens: 2000,
      thinking: { type: 'adaptive' },
      system,
      messages: [{ role: 'user', content: userContent }],
      output_config: {
        format: {
          type: 'json_schema',
          schema: {
            type: 'object',
            properties: {
              prompt: { type: 'string', description: 'The generation prompt, under 130 words' },
              note: { type: 'string', description: '1-2 friendly sentences for the non-technical user' },
            },
            required: ['prompt', 'note'],
            additionalProperties: false,
          },
        },
      },
    });
    } catch (e) { await recordGeneration({ ...rec, status: /timed out|timeout/i.test(String(e && e.message)) ? 'timed_out' : 'failed', error: e && e.message, latencyMs: Date.now() - t0 }); throw e; }

    const text = response.content.find((b) => b.type === 'text');
    if (!text) throw new Error(`no text block in response (stop_reason: ${response.stop_reason})`);
    const out = JSON.parse(text.text);
    await recordGeneration({ ...rec, status: 'succeeded', latencyMs: Date.now() - t0, usage: response.usage || null, outputAssets: [{ type: 'prompt', stage }] });
    return res.status(200).json({ stage, prompt: out.prompt, note: out.note });
  } catch (e) {
    return res.status(500).json({ error: e.message || 'director failed' });
  }
};
