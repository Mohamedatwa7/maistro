"""Regenerate docs/GRAPH.md (mermaid render of the compiled campaign graph).

Usage (from services/core):  python scripts/draw_graph.py
GitHub renders the mermaid block natively — the diagram in docs/ is always
the REAL compiled topology, not a hand-drawn approximation.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from maistro.graph.builder import build_graph  # noqa: E402
from maistro.graph.deps import GraphDeps  # noqa: E402

DOC = Path(__file__).resolve().parents[3] / "docs" / "GRAPH.md"

HEADER = """# Campaign graph — compiled topology

**Generated by `services/core/scripts/draw_graph.py` — do not edit by hand.**
Regenerate after any change to `graph/builder.py`.

Interrupt (pause) points: `await_draft`, `request_revision`,
`approval_gate`, `record_publication`, `monitor` (tick loop), `escalate`.
Each is resumed by an MCP tool call (creator), a REST call
(approver/operator), or the daily scheduler (monitor).

```mermaid
"""


def main() -> None:
    graph = build_graph(
        GraphDeps(store=None, scorer=None, metrics_source=None)  # type: ignore[arg-type]
    )
    mermaid = graph.get_graph().draw_mermaid()
    DOC.write_text(HEADER + mermaid + "\n```\n", encoding="utf-8", newline="\n")
    print(f"wrote {DOC}")


if __name__ == "__main__":
    main()
